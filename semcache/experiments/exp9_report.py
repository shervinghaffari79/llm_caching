"""
Experiment 9 -- assemble everything into a consistency report and a
point-by-point response document with the measured numbers filled in.

This does no new computation. It reads the artefacts written by exp0-exp8,
applies the arithmetic checker to the manuscript's published values, and emits
`results/CONSISTENCY_REPORT.md` and `results/RESPONSE_TO_REVIEWERS.md`.

Run: python -m semcache.experiments.exp9_report
"""
from __future__ import annotations

from pathlib import Path

import numpy as np

from .. import config as C
from ..reporting import audit_manuscript_claims, load_json, save_json
from ._common import banner


def _g(d, *path, default=None):
    for k in path:
        if d is None:
            return default
        d = d.get(k) if isinstance(d, dict) else None
    return default if d is None else d


def _load(name):
    try:
        return load_json(name)
    except FileNotFoundError:
        return None


def main() -> dict:
    banner("EXP 9 | Consistency report and response document")
    e0, e1 = _load("exp0_data_audit"), _load("exp1_latency_breakdown")
    e2, e3 = _load("exp2_end_to_end"), _load("exp3_ablation")
    e4, e5 = _load("exp4_meta_classifier"), _load("exp5_dynamic_cache")
    e6, e7 = _load("exp6_baselines"), _load("exp7_eviction")
    e8 = _load("exp8_cheap_vs_expensive")

    gen_lat = _g(e2, "llm_pool", "mean_s", default=0.854)
    audit = audit_manuscript_claims(gen_lat)

    L: list[str] = []
    A = L.append
    A("# Consistency report\n")
    A("Generated by `python -m semcache.experiments.exp9_report`. Every number "
      "below is read from a result file in `results/raw/`; nothing is "
      "hand-entered.\n")

    hw = _g(e1, "manifest", "hardware", default={})
    A(f"**Hardware.** `{hw.get('device','?')}` / {hw.get('cpu','?')} / "
      f"torch {hw.get('torch_version','?')}, {hw.get('torch_threads','?')} threads.  \n")
    A(f"**LLM.** `{C.LLM_MODEL}`, reasoning_effort=`{C.LLM_REASONING_EFFORT}`, "
      f"system prompt: \"{C.LLM_SYSTEM_PROMPT}\"\n")

    # ---- 1. the contradiction -------------------------------------------
    A("\n## 1. The latency / response-time contradiction\n")
    A(f"With the published full-stacking overhead of 539.80 ms, the average "
      f"response time cannot fall below **{audit['if_full_stacking_was_used']['hard_lower_bound_s']:.3f} s** "
      f"regardless of hit ratio, because the similarity check runs on every "
      f"request before the outcome is known. The published average of 0.311 s "
      f"is below that floor, and below the 520.76 ms cross-encoder term alone.\n")
    A(f"At the measured generation latency of {gen_lat:.3f} s, the expected "
      f"averages are:\n")
    A(f"- full stacking: **{audit['if_full_stacking_was_used']['expected_avg_response_s']:.3f} s**")
    A(f"- bi-encoder only: **{audit['if_bi_encoder_only_was_used']['expected_avg_response_s']:.3f} s**\n")
    A("Only the second is compatible with a sub-second average, which "
      "identifies which configuration the response-time experiment must have "
      "used.\n")

    if e2:
        A("\n### Re-measured, per configuration (batch size 1, one process)\n")
        A("| Configuration | bi | cross | geo | text | LGBM | Overhead/req | "
          "Hit ratio | Avg response | Speed-up | Token saving | Identity residual |")
        A("|---|---|---|---|---|---|---|---|---|---|---|---|")
        nc = e2["no_cache"]
        A(f"| No cache | - | - | - | - | - | - | - | "
          f"{nc['avg_response_time_s']:.3f} s | 1.00x | 0.0% | - |")
        for r in e2["configs"]:
            c = r["components_active"]
            def y(b): return "yes" if b else "no"
            A(f"| {r['label']} | {y(c['bi_encoder'])} | {y(c['cross_encoder'])} | "
              f"{y(c['geometric_features'])} | {y(c['text_features'])} | "
              f"{y(c['lightgbm_meta'])} | {r['avg_overhead_ms']:.2f} ms | "
              f"{r['hit_ratio_pct']:.1f}% | {r['avg_response_time_s']:.3f} s | "
              f"{r['speedup_vs_no_cache']:.2f}x | {r['token_saving_pct']:.1f}% | "
              f"{r['consistency']['residual_ms']:+.1f} ms |")
        bad = [r for r in e2["configs"] if not r["consistency"]["consistent"]]
        A(f"\nIdentity `avg_response = overhead + miss_ratio * generation` holds "
          f"for {len(e2['configs']) - len(bad)}/{len(e2['configs'])} "
          f"configurations within the {e2['configs'][0]['consistency']['tolerance_ms']:.0f} ms tolerance.\n")

    if e1:
        A("\n## 2. Latency breakdown, both batching regimes\n")
        st = e1["online_stages_ms"]
        A("| Stage | online (batch=1) mean | p95 |")
        A("|---|---|---|")
        for k, v in sorted(st.items(), key=lambda kv: -kv[1]["mean_ms"]):
            A(f"| {k} | {v['mean_ms']:.3f} ms | {v['p95_ms']:.3f} ms |")
        off = e1["offline_amortised"]
        A(f"\nOffline (batch={off['batch_size']}) amortised per pair: "
          f"bi-encoder {off['bi_encode_ms_per_pair']:.2f} ms, cross-encoder "
          f"{off['cross_encode_ms_per_pair']:.2f} ms. Batching speeds the "
          f"cross-encoder up **{e1['batching_speedup_cross']:.1f}x**, which is "
          f"why an offline-measured cost must not be quoted beside an online "
          f"serving average.\n")

    # ---- 3. ablation -----------------------------------------------------
    if e3:
        A("\n## 3. Ablation recomputed on the subset it claims\n")
        g = e3["stratified_group_kfold"]
        A(f"Subset: {e3['subset_description']['n_pairs']} pairs, "
          f"{e3['subset_description']['duplicate_ratio']*100:.0f}% duplicates, "
          f"{e3['subset_description']['n_components']} question components, "
          f"zero component/question/pair overlap with the 30k meta set.\n")
        A("| Configuration | F1 (recomputed) | dF1 vs Bi+Cross | Published Table 7 |")
        A("|---|---|---|---|")
        pub = {"Full Model": "0.8716 +/- 0.004",
               "Full Model - Cross-Encoder": "0.8709 +/- 0.004",
               "Bi + Cross": "0.8438 +/- 0.004"}
        for r in g["incremental"]:
            A(f"| {r['label']} | {r['f1_mean']:.4f} +/- {r['f1_std']:.4f} | "
              f"{r['delta_f1']:+.4f} | {pub.get(r['label'], '-')} |")
        A(f"\n30k reference recomputed under the same protocol: "
          f"F1 = {e3['reference_30k_recomputed']['f1_mean']:.4f} +/- "
          f"{e3['reference_30k_recomputed']['f1_std']:.4f}. Difference between "
          f"the 3k ablation subset and the 30k set: "
          f"**{e3['delta_ablation_vs_30k_f1']:+.4f} F1** -- the two are "
          f"distinct measurements, as they must be.\n")
        ct = g["cross_encoder_removal_test"]
        A(f"Cross-encoder removal: dF1 = {ct['mean_delta_f1']:+.4f}, bootstrap "
          f"95% CI [{ct.get('bootstrap_ci95_low', float('nan')):+.4f}, "
          f"{ct.get('bootstrap_ci95_high', float('nan')):+.4f}], paired-t "
          f"p = {ct.get('paired_t_p', float('nan')):.3f}.\n")

    # ---- 4. normalisation -------------------------------------------------
    if e4:
        A("\n## 4. Normalisation and fold construction\n")
        lk = e4["normalisation_leak_check"]
        A(e4["normalisation_statement"] + "\n")
        A(f"Measured effect of the incorrect protocol (scaler fitted before "
          f"splitting): dF1 = {lk['delta_f1']:+.5f}, dAUC = {lk['delta_auc']:+.5f}.\n")
        if e0:
            fs = e0["fold_schemes"]
            A(f"Fold construction matters more: under plain StratifiedKFold "
              f"{fs['stratified_kfold']['mean_pct_val_questions_seen']:.1f}% of "
              f"validation questions have already been seen in training via "
              f"another pair, versus "
              f"{fs['stratified_group_kfold']['mean_pct_val_questions_seen']:.1f}% "
              f"under StratifiedGroupKFold over question components. "
              f"Leakage-driven F1 inflation: "
              f"**{e4['leakage_inflation_f1']:+.4f}**.\n")
        if e0:
            au = e0["audit"]
            A(f"Row-level duplication in QQP: {au['n_exact_duplicate_rows']} exact "
              f"repeats, {au['n_mirrored_duplicate_rows']} mirrored repeats, "
              f"{au['n_self_pairs']} self-pairs, {au['n_label_conflicts']} label "
              f"conflicts; all removed before sampling "
              f"({au['n_rows_raw']} -> {au['n_rows_clean']} rows).\n")

    # ---- 5. dynamic cache -------------------------------------------------
    if e5:
        A("\n## 5. The hit ratio is a dynamic quantity\n")
        A("Same similarity model, varying only cache capacity and stream "
          "length:\n")
        A(f"- capacity effect: `{e5['sensitivity']['capacity_effect']}`")
        A(f"- warm-up effect: `{e5['sensitivity']['warmup_effect']}`\n")
        A("A static pair-level score cannot vary along either axis, which is "
          "why the reported figure must come from a stream simulation.\n")

    # ---- 6. baselines -----------------------------------------------------
    if e6:
        A("\n## 6. Comparison with published semantic caches\n")
        A("| System | Hit ratio | Hit precision | Correct miss (distractors) | "
          "Token saving | Overhead/req | Avg response |")
        A("|---|---|---|---|---|---|---|")
        for r in e6["systems"]:
            A(f"| {r['label']} | {r['hit_ratio_pct']:.1f}% | "
              f"{r['precision_of_hits_pct']:.1f}% | "
              f"{r.get('correct_miss_ratio_on_hard_negatives_pct', float('nan')):.1f}% | "
              f"{r['token_saving_pct']:.1f}% | {r['avg_overhead_ms']:.2f} ms | "
              f"{r['avg_response_time_s']:.3f} s |")
        A("\n" + e6["fairness_statement"] + "\n")
        A("\n**ContextCache.** " + e6["contextcache_caveat"] + "\n")

    # ---- 7. eviction ------------------------------------------------------
    if e7 and e7.get("weight_sensitivity"):
        s = e7["weight_sensitivity"]
        A("\n## 7. Eviction policy and weight sensitivity\n")
        A(f"Across {s['grid_points']} weight settings on the simplex, hit ratio "
          f"spans {s['spread_pp']:.1f} percentage points (std {s['std_pp']:.2f}). "
          f"{s['fraction_of_grid_beating_lru']*100:.0f}% of settings still beat "
          f"LRU at capacity 500. The paper's weights "
          f"(0.28/0.38/0.34) give {s['paper_weights']['hit_ratio_pct']:.1f}%, "
          f"best on the grid is {s['best']['hit_ratio_pct']:.1f}%.\n")

    # ---- 8. title ---------------------------------------------------------
    if e8:
        A("\n## 8. Does the ablation support the title?\n")
        A(e8["verdict"]["statement"] + "\n")
        A("| Component | Class | dF1 | Added latency | dF1 per 100 ms |")
        A("|---|---|---|---|---|")
        for r in e8["rows"]:
            f = r["f1_per_100ms"]
            A(f"| {r['component']} | {r['class']} | {r['delta_f1']:+.4f} | "
              f"{r['added_ms']:.3f} ms | "
              f"{'-' if not np.isfinite(f) else f'{f:+.4f}'} |")
        A(f"\n**Definitions.** Cheap: {e8['definitions']['cheap_definition']} "
          f"Expensive: {e8['definitions']['expensive_definition']}\n")
        A("\n**Why keep the cross-encoder at all?** " +
          e8["why_keep_the_cross_encoder"] + "\n")

    report = "\n".join(L)
    p = C.RESULTS_DIR / "CONSISTENCY_REPORT.md"
    p.write_text(report, encoding="utf8")
    print(f"  wrote {p}")

    save_json({"manuscript_claim_audit": audit,
               "generation_latency_used_s": gen_lat}, "exp9_claim_audit")
    return {"report_path": str(p), "audit": audit}


if __name__ == "__main__":
    main()

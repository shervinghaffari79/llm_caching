"""
Experiment 38 -- transfer of the QQP-trained decision layer to a second domain:
SemBenchmarkLmArena (chat prompts).

The benchmark samples 3,500 LM-Arena user prompts and expands each into up to
24 variants generated by GPT-4.1-nano; the class id is the seed prompt, and a
hit is correct when the served entry has the query's class. Its repeats are
therefore synthetic paraphrases, not observed traffic, and it says nothing
about admission or capacity. It does test what the real search log tests for
the decision layer: how the QQP-trained operating points (C1 cosine 0.726,
C2 probability 0.5) behave on text from another domain, and how far the
precision-coverage curve of each configuration moves.

Protocol, fixed before the run:
  stream   a seeded random permutation (seed 42) of the 63,796 rows, first n
           requests (n = 30,000), served by an unbounded cache that starts empty
           (the same online protocol as experiment 22);
  models   QQP-trained only (meta-classifier of the shared QQP training set);
           no model or threshold sees LmArena labels;
  configs  C1 over cosine thresholds {0.60 ... 0.95}, C2 over probability
           thresholds {0.1 ... 0.97}; C4/C5 are not run (the cross-encoder over
           tens of thousands of pairs is impractical on CPU, and C1/C2 carry
           the transfer question);
  record   hit ratio and precision per configuration, blocks of 5,000, and the
           per-request hit and correctness flags, so that calibration on a
           labeled prefix can be analysed afterwards without rerunning.

Vectors: data/external/lmarena_vectors.npz (all-mpnet-base-v2, normalized,
float32; encoded once on a Colab T4).

Run: python -m semcache.experiments.exp38_lmarena_transfer --n 30000
"""
from __future__ import annotations

import argparse

import numpy as np
import pandas as pd

from .. import config as C
from ..encoders import warmup
from ..workload import StreamEvent, Workload
from ._common import banner, hardware_manifest, memoized_encoders, save_result, serve, train_metas
from .exp22_searchqueries import KEEP, _backend, blocks

DATA = C.DATA_DIR / "external" / "sembenchmark_lmarena.parquet"
VECS = C.DATA_DIR / "external" / "lmarena_vectors.npz"
SOURCE = "https://huggingface.co/datasets/vCache/SemBenchmarkLmArena"
BI_GRID = (0.60, 0.70, C.BI_COSINE_THRESHOLD, 0.75, 0.80, 0.85, 0.90, 0.95)
META_GRID = (0.1, 0.3, C.META_PROB_THRESHOLD, 0.7, 0.9, 0.97)
ORDER_SEED = 42


def load_stream(n: int) -> Workload:
    df = pd.read_parquet(DATA)
    df = df.iloc[np.random.default_rng(ORDER_SEED).permutation(len(df))].iloc[:n]
    seen_g: set[int] = set()
    seen_q: set[str] = set()
    events = []
    for i, (q, g) in enumerate(zip(df["prompt"].astype(str), df["id_set"])):
        g = int(g)
        events.append(StreamEvent(step=i, query=q, topic_id=g, is_repeat=g in seen_g, is_exact=q in seen_q,
                                  is_hard_negative=False, session_id=i, turn=0))
        seen_g.add(g)
        seen_q.add(q)
    rep = sum(e.is_repeat for e in events)
    ex = sum(e.is_exact for e in events)
    meta = {"source": SOURCE, "n_events": len(events), "n_unique_queries": len({e.query for e in events}),
            "n_topics": len(seen_g), "repeat_rate_pct": 100.0 * rep / len(events),
            "exact_repeat_rate_pct": 100.0 * ex / len(events),
            "paraphrase_repeat_rate_pct": 100.0 * (rep - ex) / len(events),
            "hard_negative_rate_pct": None, "order": f"random permutation, seed {ORDER_SEED}"}
    return Workload(events=events, meta=meta)


def main(n: int = 30000, seed: int = C.SEED, tag: str = "") -> dict:
    banner(f"EXP 38 | SemBenchmarkLmArena transfer, {n} requests")
    warmup(include_cross=False)
    wl = load_stream(n)
    print(f"  {wl.meta['n_events']} requests, {wl.meta['n_topics']} classes, "
          f"{wl.meta['repeat_rate_pct']:.1f}% repeats ({wl.meta['exact_repeat_rate_pct']:.1f}% verbatim)", flush=True)
    z = np.load(VECS, allow_pickle=True)
    vecs = dict(zip(z["queries"].tolist(), z["vectors"]))
    metas = train_metas(seed=seed)
    rep = np.array([e.is_repeat for e in wl.events])
    res: dict[str, dict] = {}

    def record(name, stats, events):
        bl = blocks(events)
        for b in bl:
            b["repeat_rate_pct"] = 100.0 * float(rep[b["start"]:b["start"] + b["n"]].mean())
        res[name] = {"stats": {k: stats.get(k) for k in KEEP}, "blocks": bl,
                     "hit": [int(bool(e["hit"])) for e in events],
                     "correct": [int(bool(e["correct"])) if e["hit"] else 0 for e in events]}
        print(f"  {name:12s} hit {stats['hit_ratio_pct']:5.1f}%  prec {stats['precision_of_hits_pct']:5.1f}%",
              flush=True)

    with memoized_encoders() as memo:
        memo._bi_cache.update({q: vecs[q] for q in wl.queries()})
        for thr in BI_GRID:
            r = serve("C1_bi_only", wl, _backend(seed), metas, bi_threshold=thr)
            record(f"C1_t{thr:g}", r.stats, r.per_event)
        for thr in META_GRID:
            r = serve("C2_bi_geo_lgb", wl, _backend(seed), metas, meta_threshold=thr)
            record(f"C2_p{thr:g}", r.stats, r.per_event)

    out = {"manifest": hardware_manifest({"dataset": SOURCE, "n_stream": n, "order_seed": ORDER_SEED,
                                          "latency_valid": False, "token_counts_valid": False,
                                          "bi_grid": list(BI_GRID), "meta_grid": list(META_GRID)}, seed=seed),
           "workload": wl.meta, "results": res}
    save_result(out, "exp38_lmarena_transfer", tag=tag or f"n{n}")
    return out


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=30000)
    ap.add_argument("--tag", default="")
    a = ap.parse_args()
    main(a.n, tag=a.tag)

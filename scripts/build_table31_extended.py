"""Write results/revision/table31_extended.tex from the saved per-window scores (same pooling as scripts/tables_extra_baselines.py).
Usage: python scripts/build_table31_extended.py"""
import json
import numpy as np

R = "results/raw/revision/"
LAMS = ("0", "1", "2", "5", "10")


def load(files):
    pw = {}
    for f in files:
        d = json.load(open(R + f))
        m = max(d["per_window_scores"], key=int)
        for lam, fams in d["per_window_scores"][m].items():
            for fam, v in fams.items():
                pw.setdefault(lam, {}).setdefault(fam, []).extend(v)
    return pw


def over(pw, files):
    for lam, fams in load(files).items():
        for fam, v in fams.items():
            assert len(v) == len(pw[lam].get(fam, v))
            pw[lam][fam] = v
    return pw


sl = load(["exp54_searchlog_extra_v2.json", "exp37_causal_reusegate_cpu_rot1_extra.json", "exp37_causal_reusegate_cpu_rot2_extra.json"])
lm = over(load([f"exp54_lmarena_rot{r}_extra.json" for r in range(3)]), [f"exp37_causal_reusegate_cpu_lmarena_rot{r}_solaro.json" for r in range(3)])
rows = [("LRU", "LRU"), ("LFU", "LFU"), ("SphereLFU", "SphereLFU"), ("LeCaR", "LeCaR"), ("Semantic Decay", "SemanticDecay_fixed"),
        ("W-TinyLFU (exact count)", "WTinyLFU"), ("FIFO", "FIFO"), ("ARC", "ARC"), ("S3-FIFO", "S3FIFO"), ("SIEVE", "SIEVE"), ("GDSF", "GDSF"),
        ("DynamicAdaptiveClimb", "DynamicAdaptiveClimb"),
        ("SOLAR-E$^{\\dagger}$", "SOLAR-E"), ("SOLAR-A$^{\\dagger}$", "SOLAR-A"), ("SOLAR$^{\\dagger}$", "SOLAR"),
        ("SOLAR-E$^{\\ddagger}$", "SOLARo-E"), ("SOLAR-A$^{\\ddagger}$", "SOLARo-A"), ("SOLAR$^{\\ddagger}$", "SOLARo"),
        ("ReuseGate", "Learned[match]"), ("ReuseGate-R", "Learned[group]")]
n_sl, n_lm = len(sl["0"]["LRU"]), len(lm["0"]["LRU"])
out = ["% Extended Table 31 (generated by scripts/build_table31_extended.py): score = correct-hit % - lambda x false-hit %, mean over cache capacities and evaluation windows.",
       f"% Search log: {n_sl} windows (three block rotations); LmArena: {n_lm} windows (three rotations). $^\\dagger$ first reimplementation (tuned on tuning windows), $^\\ddagger$ constants of the authors' code.",
       "% ReuseGate / ReuseGate-R / W-TinyLFU come from the same Colab runs as the other policies and can differ from the main tables (Modal runs) by up to about 0.1 points.",
       "\\begin{tabular}{lrrrrr|rrrrr}", "\\toprule", "Policy & \\multicolumn{5}{c|}{Search log, $\\lambda$} & \\multicolumn{5}{c}{LmArena, $\\lambda$}\\\\",
       " & 0 & 1 & 2 & 5 & 10 & 0 & 1 & 2 & 5 & 10\\\\", "\\midrule"]
for lab, fam in rows:
    cells = [f"{np.mean(sl[l][fam]):.2f}" for l in LAMS] + [f"{np.mean(lm[l][fam]):.2f}" for l in LAMS]
    out.append(f"{lab} & " + " & ".join(cells) + "\\\\")
out += ["\\bottomrule", "\\end{tabular}"]
open("results/revision/table31_extended.tex", "w").write("\n".join(out) + "\n")
print("\n".join(out))

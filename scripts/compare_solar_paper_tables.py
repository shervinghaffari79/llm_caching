"""Compare the authors' synthetic-workload tables (arXiv:2607.00394, Tables 8, 9, 10, 11; transcribed by hand) with our D1 reproduction (authors' code, unmodified).
Usage: python compare_solar_paper_tables.py <dir with synthD1, synthD1_rn, synthD1_frozen> <out.md>"""
import json, re, sys
from collections import defaultdict
from pathlib import Path
import numpy as np

root, out = Path(sys.argv[1]), Path(sys.argv[2])
NAME = re.compile(r"^(?P<m>[a-z_0-9]+?)__(?P<cfg>.+)__seed(?P<s>\d+)\.json$")


def load(d):
    R = defaultdict(dict)
    for f in Path(d).rglob("*__seed*.json"):
        m = NAME.match(f.name)
        if m:
            R[(f.parent.name, m["cfg"], m["m"])][int(m["s"])] = json.load(open(f))
    return R


D1, RN, FZ = load(root / "synthD1"), load(root / "synthD1_rn"), load(root / "synthD1_frozen")
mean = lambda recs, k="avg_hit_rate": float(np.mean([r[k] for r in recs.values()]))
rows = []  # (table, cell, paper, ours, tol)

# Table 8: cycling, K=10, 3-seed avg (two decimals)
T8 = {"fifo": [.90, .00, .00, .00, .00], "lru": [.38, .17, .08, .02, .00], "lfu": [.60, .52, .40, .27, .16], "solar_e": [.55, .39, .29, .20, .11], "solar_a": [.70, .54, .40, .27, .16], "solar": [.69, .54, .40, .26, .16]}
for m, vals in T8.items():
    for mm, v in zip((10, 15, 20, 30, 50), vals):
        rows.append(("Table 8 cycling", f"{m} m={mm}", v, mean(D1[("cycling", f"K10_m{mm}", m)]), 0.01))
# Table 9: working-set sweep, uniform (two decimals); the paper's row "SOLAR"
T9 = {"fifo": [.31, .49, .62, .73, .86, .94, .97, .97], "solar": [.33, .58, .71, .81, .85, .95, .95, .95]}
for m, vals in T9.items():
    for K, v in zip((5, 10, 15, 20, 30, 50, 100, 200), vals):
        rows.append(("Table 9 working set", f"{m} K={K}", v, mean(D1[("working_set", f"K{K}_distuniform", m)]), 0.01))
# Table 11: stream-mode retrieval noise (three decimals)
T11 = {"fifo": [.075, .089, .087, .090], "solar": [.083, .094, .094, .094]}
for m, vals in T11.items():
    for K, v in zip((200, 500, 1000, 5000), vals):
        rows.append(("Table 11 stream", f"{m} K={K}", v, mean(RN[("retrieval_noise_stream", f"K{K}_intra0.15_inter0.30_stream", m)]), 0.001))
# Table 10: frozen pool probe (three decimals): hit rate and precision@3
T10 = {"hit": [.067, .170, .186, .201, .195, .090], "prec": [.022, .058, .065, .070, .068, .030]}
frozen_keys = sorted({(d, c, m) for (d, c, m) in FZ})
for i, K in enumerate((50, 200, 500, 1000, 2000, 5000)):
    cands = [k for k in frozen_keys if re.search(rf"K{K}(_|$)", k[1])]
    if cands:
        recs = FZ[cands[0]]
        rows.append(("Table 10 frozen pool", f"hit K={K}", T10["hit"][i], mean(recs), 0.001))
        rows.append(("Table 10 frozen pool", f"prec@3 K={K}", T10["prec"][i], mean(recs, "avg_precision_at_k"), 0.001))

lines = ["# Our reproduction against the SOLAR paper's synthetic tables (generated by scripts/compare_solar_paper_tables.py)\n",
         "Paper values were transcribed by hand from arXiv:2607.00394 (Tables 8, 9, 10, 11). Ours: authors' code unmodified (D1), 3 seeds 42/1337/2024. A cell matches when |ours - paper| <= tolerance "
         "(0.01 for two-decimal tables, 0.001 for three-decimal tables; pre-registered).\n"]
bytab = defaultdict(list)
for r in rows:
    bytab[r[0]].append(r)
for t, rs in bytab.items():
    ok = sum(abs(o - p) <= tol + 1e-9 for _, _, p, o, tol in rs)
    lines.append(f"## {t}: {ok} of {len(rs)} cells match\n")
    bad = [(c, p, o) for _, c, p, o, tol in rs if abs(o - p) > tol + 1e-9]
    if bad:
        lines.append("| cell | paper | ours | diff |\n|---|---|---|---|")
        lines += [f"| {c} | {p:.3f} | {o:.3f} | {o - p:+.3f} |" for c, p, o in bad]
    else:
        lines.append("No differing cell.")
    lines.append("")
    lines.append("<details><summary>all cells</summary>\n\n| cell | paper | ours |\n|---|---|---|")
    lines += [f"| {c} | {p:.3f} | {o:.3f} |" for _, c, p, o, _ in rs]
    lines.append("\n</details>\n")
tot = sum(abs(o - p) <= tol + 1e-9 for _, _, p, o, tol in rows)
lines.insert(2, f"**Overall: {tot} of {len(rows)} transcribed cells match.**\n")
out.write_text("\n".join(lines))
print(out, tot, len(rows))

"""Aggregate Stage D (SOLAR synthetic stress tests). Usage: python aggregate_solar_synth.py <root with synthD1, synthD1_rn, synthD2, synthD2_rn> <out.md>"""
import json, re, sys
from collections import defaultdict
from pathlib import Path
import numpy as np

root, out = Path(sys.argv[1]), Path(sys.argv[2])
NAME = re.compile(r"^(?P<m>[a-z_0-9]+?)__(?P<cfg>.+)__seed(?P<s>\d+)\.json$")
THEIRS = ["fifo", "lru", "lfu", "arc", "solar_e", "solar_a", "solar", "embedder_unlimited"]
ALL = THEIRS[:-1] + ["reusegate_e", "reusegate", "embedder_unlimited"]


def load(d):
    """-> {(subdir, cfg, method): {seed: record}}"""
    R = defaultdict(dict)
    for f in Path(d).rglob("*__seed*.json"):
        m = NAME.match(f.name)
        if not m:
            continue
        sub = str(f.parent.relative_to(d))
        R[(sub, m["cfg"], m["m"])][int(m["s"])] = json.load(open(f))
    return R


D1, D1r, D2, D2r = (load(root / x) for x in ("synthD1", "synthD1_rn", "synthD2", "synthD2_rn"))
D1.update(D1r); D2.update(D2r)


def ms(recs, key="avg_hit_rate"):
    v = [r[key] for r in recs.values()]
    return np.mean(v), (np.std(v, ddof=1) if len(v) > 1 else float("nan")), len(v)


lines = ["# Stage D results: SOLAR's synthetic stress tests (generated by scripts/aggregate_solar_synth.py)\n"]

# 1. equivalence of D1 (authors' code) and D2 (patched copy) on the authors' methods
n = same = 0
bad = []
for k, recs in D1.items():
    if k in D2:
        for s, r in recs.items():
            if s in D2[k]:
                n += 1
                if r["per_step_hits"] == D2[k][s]["per_step_hits"] and r["per_step_f1"] == D2[k][s]["per_step_f1"]:
                    same += 1
                else:
                    bad.append((k, s))
lines.append(f"## 0. Does the patched copy reproduce the authors' code?\n\n{same} of {n} (config, method, seed) runs have identical per-step hits and F1 in D1 (authors' code, unmodified) and D2 (patched copy). Mismatches: {bad[:5] if bad else 'none'}.\n")


def table(title, sub, cfgs, label, methods=ALL, key="avg_hit_rate", D=D2, fmt="{:.3f}"):
    lines.append(f"### {title}\n")
    lines.append("| method | " + " | ".join(label(c) for c in cfgs) + " |")
    lines.append("|---|" + "---|" * len(cfgs))
    for m in methods:
        row = []
        for c in cfgs:
            recs = D.get((sub, c, m))
            if not recs:
                row.append("n/a"); continue
            a, s, k = ms(recs, key)
            row.append(fmt.format(a) + (f" ± {s:.3f}" if k > 1 else ""))
        lines.append(f"| {m} | " + " | ".join(row) + " |")
    lines.append("")


def cfgs_of(sub, D=D2):
    return sorted({c for (s, c, m) in D if s == sub})


def num(c, pat):
    return int(re.search(pat, c).group(1))


lines.append("## 1. Cycling (capacity K = 10; the working set cycles through m items, m/K = 1..5)\n")
cyc = sorted(cfgs_of("cycling"), key=lambda c: num(c, r"_m(\d+)"))
table("Hit rate", "cycling", cyc, lambda c: f"m={num(c, r'_m(\d+)')}")
table("Admission rate (store rate)", "cycling", cyc, lambda c: f"m={num(c, r'_m(\d+)')}", key="store_rate")

for sub, name in (("working_set", "uniform"), ("zipf/working_set", "Zipf")):
    lines.append(f"## 2. Working-set sweep, {name} topic popularity (cache capacity K varies)\n")
    ws = sorted(cfgs_of(sub), key=lambda c: num(c, r"^K(\d+)"))
    table(f"Hit rate ({name})", sub, ws, lambda c: f"K={num(c, r'^K(\d+)')}")
    # crossover: smallest K from which method >= fifo - 0.005 for all larger K
    lines.append(f"Hit-rate gap to FIFO ({name}), mean over seeds (paired by seed):\n")
    lines.append("| method | " + " | ".join(f"K={num(c, r'^K(\d+)')}" for c in ws) + " |")
    lines.append("|---|" + "---|" * len(ws))
    for m in ALL:
        if m == "fifo":
            continue
        row = []
        for c in ws:
            a, b = D2.get((sub, c, m)), D2.get((sub, c, "fifo"))
            if not a or not b:
                row.append("n/a"); continue
            d = [a[s]["avg_hit_rate"] - b[s]["avg_hit_rate"] for s in a if s in b]
            row.append(f"{np.mean(d):+.3f}")
        lines.append(f"| {m} | " + " | ".join(row) + " |")
    lines.append("")

lines.append("## 3. Topic drift (K = 20; phases of length L, overlap = number of topics kept between phases)\n")
subs = [("topic_drift", c) for c in sorted(cfgs_of("topic_drift"), key=lambda c: num(c, r"plen(\d+)"))] + [("ov0/topic_drift", c) for c in cfgs_of("ov0/topic_drift")] + [("ov2/topic_drift", c) for c in cfgs_of("ov2/topic_drift")]
lines.append("| method | " + " | ".join(re.sub(r"K20_", "", c) for _, c in subs) + " |")
lines.append("|---|" + "---|" * len(subs))
for m in ALL:
    row = []
    for s, c in subs:
        recs = D2.get((s, c, m))
        row.append("n/a" if not recs else "{:.3f} ± {:.3f}".format(*ms(recs)[:2]))
    lines.append(f"| {m} | " + " | ".join(row) + " |")
lines.append("")
# recovery: mean hit rate over the 20 steps after each phase boundary versus the rest of the phase
lines.append("Recovery after a phase boundary (plen 100, overlap 1): mean hit rate in the 20 steps after a boundary / in the remainder of the phase.\n")
lines.append("| method | first 20 steps | rest of phase | ratio |\n|---|---|---|---|")
for m in ALL:
    recs = D2.get(("topic_drift", "K20_plen100_ov1", m))
    if not recs:
        continue
    a, b = [], []
    for r in recs.values():
        h = np.array(r["per_step_hits"], float)
        bd = r["workload_params"]["phase_boundaries"]
        mask = np.zeros(len(h), bool)
        for x in bd:
            mask[x:x + 20] = True
        a.append(h[mask].mean()); b.append(h[~mask][100:].mean() if len(h) > 100 else h[~mask].mean())
    lines.append(f"| {m} | {np.mean(a):.3f} | {np.mean(b):.3f} | {np.mean(a) / np.mean(b):.2f} |")
lines.append("")

lines.append("## 4. Retrieval-noise stream (5,000 warm-up requests, then 1,000 evaluation steps; many distractor items)\n")
rn = sorted(cfgs_of("retrieval_noise_stream"), key=lambda c: num(c, r"^K(\d+)"))
for key, t in (("avg_hit_rate", "Hit rate"), ("avg_precision_at_k", "Precision@3"), ("store_rate", "Admission rate")):
    table(t, "retrieval_noise_stream", rn, lambda c: f"K={num(c, r'^K(\d+)')}", key=key)

# 5. sensitivity (labelled; not the pre-registered result)
lines.append("## 5. Sensitivity of ReuseGate (labelled: radius 0.3 / 0.7 pre-registered as sensitivity; aging period 100 is exploratory, chosen after seeing the drift failure)\n")
SENS = {"default (r=0.5, period 1000)": D2, "radius 0.3": load(root / "synthD3_r03"), "radius 0.7": load(root / "synthD3_r07"), "period 100 (exploratory)": load(root / "synthD3_p100")}
sel = [("cycling", "K10_m10", "cycling m=10"), ("cycling", "K10_m30", "cycling m=30"), ("working_set", "K20_distuniform", "working set uniform K=20"),
       ("working_set", "K50_distuniform", "working set uniform K=50"), ("zipf/working_set", "K10_distzipf", "working set Zipf K=10"),
       ("topic_drift", "K20_plen100_ov1", "drift plen 100"), ("topic_drift", "K20_plen50_ov1", "drift plen 50")]
for m in ("reusegate", "reusegate_e"):
    lines.append(f"### {m}: hit rate (FIFO in the last row)\n")
    lines.append("| setting | " + " | ".join(t for _, _, t in sel) + " |")
    lines.append("|---|" + "---|" * len(sel))
    for name, D in SENS.items():
        lines.append(f"| {name} | " + " | ".join("n/a" if not D.get((a, b, m)) else "{:.3f}".format(ms(D[(a, b, m)])[0]) for a, b, _ in sel) + " |")
    lines.append("| fifo | " + " | ".join("{:.3f}".format(ms(D2[(a, b, "fifo")])[0]) for a, b, _ in sel) + " |")
    lines.append("")

out.write_text("\n".join(lines))
print("wrote", out, len(lines), "lines")

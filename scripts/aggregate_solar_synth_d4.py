"""Stage D2 (10 seeds, tuned radius). Usage: python aggregate_solar_synth_d4.py <root with D4_default, D4_tuned_global, D4_tuned_perfamily, tune, tuned_radius.json> <out.md>"""
import json, re, sys
from collections import defaultdict
from pathlib import Path
import numpy as np

root, out = Path(sys.argv[1]), Path(sys.argv[2])
NAME = re.compile(r"^(?P<m>[a-z_0-9]+?)__(?P<cfg>.+)__seed(?P<s>\d+)\.json$")
T9 = 2.2622  # t quantile, 9 degrees of freedom, 97.5%


def load(d):
    R = defaultdict(dict)
    for f in Path(d).rglob("*__seed*.json"):
        m = NAME.match(f.name)
        if m:
            fam = f.relative_to(d).parts[0]
            sub = "/".join(f.relative_to(d).parts[1:-1])
            R[(fam, sub, m["cfg"], m["m"])][int(m["s"])] = json.load(open(f))["avg_hit_rate"]
    return R


DEF, TG, TF = load(root / "D4_default"), load(root / "D4_tuned_global"), load(root / "D4_tuned_perfamily")
sel = json.load(open(root / "tuned_radius.json"))
cfgs = sorted({(f, s, c) for (f, s, c, m) in DEF}, key=lambda x: (["cycling", "drift", "ws_uniform", "ws_zipf"].index(x[0]), x[1], int(re.findall(r"\d+", x[2].replace("K20_", "") if x[0] == "drift" else x[2])[0]) if re.findall(r"\d+", x[2]) else 0, x[2]))


def lab(f, s, c):
    if f == "cycling": return "cycling " + c.split("_")[1]
    if f == "drift": return "drift " + re.sub("K20_", "", c)
    return ("ws-uniform " if f == "ws_uniform" else "ws-Zipf ") + c.split("_")[0]


def gap(a, b):
    ss = sorted(set(a) & set(b))
    d = np.array([a[s] - b[s] for s in ss])
    h = T9 * d.std(ddof=1) / np.sqrt(len(d)) if len(d) == 10 else float("nan")
    return d.mean(), d.mean() - h, d.mean() + h


def cell(g):
    m, lo, hi = g
    mark = "+" if lo > 0 else ("-" if hi < 0 else "")
    return f"{m:+.3f} [{lo:+.3f}, {hi:+.3f}]{mark}"


lines = ["# Stage D2 results: 10 seeds, tuned ReuseGate radius (generated by scripts/aggregate_solar_synth_d4.py)\n",
         f"Radius selection (tuning seeds 101-103, pre-registered rule): global radius **{sel['global_radius']}**; per family {sel['per_family_radius']}. Family-mean hit rate per radius (average over the four families): "
         + ", ".join(f"{r}: {v:.4f}" for r, v in sel["score"].items()) + ".\n",
         "Gaps are mean paired differences in hit rate over 10 seeds with a 95% t-interval (9 df); a trailing + or - marks an interval that excludes 0 (descriptive; no multiplicity correction).\n"]
for ref, name in (("fifo", "FIFO"), ("solar_a", "SOLAR-A"), ("solar", "SOLAR")):
    lines.append(f"## ReuseGate minus {name}\n")
    lines.append("| configuration | default radius 0.5 | tuned global radius | tuned per-family radius |\n|---|---|---|---|")
    cnt = {k: [0, 0, 0] for k in ("d", "g", "f")}
    for f, s, c in cfgs:
        b = DEF[(f, s, c, ref)]
        gs = [gap(DEF[(f, s, c, "reusegate")], b), gap(TG[(f, s, c, "reusegate")], b), gap(TF[(f, s, c, "reusegate")], b)]
        for k, g in zip("dgf", gs):
            cnt[k][0 if g[1] > 0 else (1 if g[2] < 0 else 2)] += 1
        lines.append(f"| {lab(f, s, c)} | " + " | ".join(cell(g) for g in gs) + " |")
    n = len(cfgs)
    lines.append(f"\nOut of {n} configurations (ReuseGate better / worse / not distinguishable): default {cnt['d']}, tuned global {cnt['g']}, tuned per family {cnt['f']}.\n")

lines.append("## Mean hit rate over 10 seeds (all methods at default radius; ReuseGate also at the tuned radius)\n")
meths = ["fifo", "lru", "lfu", "arc", "solar_e", "solar_a", "solar", "reusegate", "reusegate_e", "embedder_unlimited"]
lines.append("| configuration | " + " | ".join(meths) + " | reusegate tuned (global) | reusegate_e tuned (global) |\n|---|" + "---|" * (len(meths) + 2))
for f, s, c in cfgs:
    row = [f"{np.mean(list(DEF[(f, s, c, m)].values())):.3f}" for m in meths]
    row += [f"{np.mean(list(TG[(f, s, c, m)].values())):.3f}" for m in ("reusegate", "reusegate_e")]
    lines.append(f"| {lab(f, s, c)} | " + " | ".join(row) + " |")
out.write_text("\n".join(lines))
print("wrote", out)

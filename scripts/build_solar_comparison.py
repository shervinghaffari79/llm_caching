def tint(d):
    d = np.asarray(d, float)
    if len(d) < 3 or d.std(ddof=1) == 0:
        return d.mean(), (np.nan, np.nan), np.nan
    se = d.std(ddof=1) / np.sqrt(len(d))
    h = stats.t.ppf(0.975, len(d) - 1) * se
    return d.mean(), (d.mean() - h, d.mean() + h), float(2 * stats.t.sf(abs(d.mean() / se), len(d) - 1))


def per_seed(v):
    seeds = sorted({s for _, s in v})
    return [np.mean([x for (d, s2), x in v.items() if s2 == s]) for s in seeds]



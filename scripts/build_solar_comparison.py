# cache-stream comparison
def _load_pw(files):
    pw = {}
    for f in files:
        d = json.load(open(ROOT + f))
        Rm = max(d["per_window_scores"], key=int)
        for lam, fams in d["per_window_scores"][Rm].items():
            for fam, v in fams.items():
                pw.setdefault(lam, {}).setdefault(fam, []).extend(v)
    return pw


def pw_table(files, title, extra_note="", over=()):
    """over: files whose families replace those of `files` (same windows), so ReuseGate is paired with a ReuseGate from the same run."""
    pw = _load_pw(files)
    for lam_, fams_ in _load_pw(over).items():
        for fam_, v_ in fams_.items():
            assert len(v_) == len(pw[lam_].get(fam_, v_)), (fam_, len(v_))
            pw[lam_][fam_] = v_
    lam = list(pw)
    out = [f"### {title}", "", extra_note, "", "| policy | " + " | ".join(f"λ={l}" for l in lam) + " |", "|---|" + "---|" * len(lam)]
    order = ["Learned[match]", "Learned[group]", "WTinyLFU", "SOLAR-E", "SOLAR-A", "SOLAR", "SOLARo-E", "SOLARo-A", "SOLARo", "GDSF", "S3FIFO", "SIEVE",
             "DynamicAdaptiveClimb", "ARC", "FIFO", "LRU", "LFU"]
    lab = {"Learned[match]": "ReuseGate (label-free)", "Learned[group]": "ReuseGate-R (uses earlier group labels)",
           "SOLAR-E": "SOLAR-E (first reimplementation)", "SOLAR-A": "SOLAR-A (first reimplementation)", "SOLAR": "SOLAR (first reimplementation)",
           "SOLARo-E": "SOLAR-E (reference constants)", "SOLARo-A": "SOLAR-A (reference constants)", "SOLARo": "SOLAR (reference constants)"}
    for f in order:
        if f in pw[lam[0]]:
            out.append(f"| {lab.get(f, f)} | " + " | ".join(f"{np.mean(pw[l][f]):.2f}" for l in lam) + " |")
    out.append("")
    out.append("ReuseGate minus SOLAR-A, delta [95% CI] over evaluation windows:")
    out.append("")
    out.append("| variant | SOLAR-A version | " + " | ".join(f"λ={l}" for l in lam) + " |")
    out.append("|---|---|" + "---|" * len(lam))
    for var, vn in (("Learned[match]", "ReuseGate"), ("Learned[group]", "ReuseGate-R")):
        for b, bn in (("SOLAR-A", "first"), ("SOLARo-A", "reference constants")):
            if b not in pw[lam[0]]:
                continue
            cells = []
            for l in lam:
                m, ci, p = tint(np.array(pw[l][var]) - np.array(pw[l][b]))
                cells.append(f"{m:+.2f} [{ci[0]:+.2f}, {ci[1]:+.2f}]")
            out.append(f"| {vn} | {bn} | " + " | ".join(cells) + " |")
    out.append("")
    return out


